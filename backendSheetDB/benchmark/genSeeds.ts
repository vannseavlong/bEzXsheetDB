import fs from 'fs';
import path from 'path';
import { mulberry32, makeRow } from './lib/prng';

// Incremental checkpoints: each step adds only *new* sku values on top of the
// previous step's cumulative total, so seeding step N after step N-1 grows the
// live table from the previous checkpoint to the next rather than re-inserting
// rows that are already there. Run in order: 1k -> 10k -> 25k -> 50k -> 100k.
const STEPS = [
  { name: '01-to-1k', from: 1, to: 1_000 },
  { name: '02-to-10k', from: 1_001, to: 10_000 },
  { name: '03-to-25k', from: 10_001, to: 25_000 },
  { name: '04-to-50k', from: 25_001, to: 50_000 },
  { name: '05-to-100k', from: 50_001, to: 100_000 },
];

const SEED = 20260801; // fixed seed -> reproducible data across regenerations
const rand = mulberry32(SEED);
const outDir = path.resolve(process.cwd(), 'seeds');

for (const step of STEPS) {
  const rows: Record<string, unknown>[] = [];
  for (let i = step.from; i <= step.to; i++) {
    const base = makeRow(rand, i);
    rows.push({
      sku: `sku-bench-${String(i).padStart(7, '0')}`,
      ...base,
    });
  }

  const count = step.to - step.from + 1;
  const filePath = path.join(outDir, `bench-records-${step.name}.ts`);
  const contents =
    `// Auto-generated by benchmark/genSeeds.ts — do not hand-edit.\n` +
    `// ${count} rows, sku range [${step.from}, ${step.to}], seed ${SEED}.\n` +
    `export default { benchmark_records: ${JSON.stringify(rows)} };\n`;

  fs.writeFileSync(filePath, contents);
  console.log(`wrote ${filePath} (${count} rows)`);
}
